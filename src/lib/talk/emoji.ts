export function emojiList(group: string): string[] {
  return EMOJI_GROUPS.find((g) => g.key === group)?.list.split(" ") ?? [];
}

const RECENT_KEY = "asatalk-recent-emoji";
export function recentEmoji(): string[] {
  try {
    return JSON.parse(localStorage.getItem(RECENT_KEY) ?? "[]") as string[];
  } catch {
    return [];
  }
}
export function pushRecentEmoji(e: string) {
  try {
    const list = [e, ...recentEmoji().filter((x) => x !== e)].slice(0, 32);
    localStorage.setItem(RECENT_KEY, JSON.stringify(list));
  } catch {
    /* ignore */
  }
}

/** True when the text is only emoji (rendered large, like Telegram). */
export function isOnlyEmoji(text: string): boolean {
  const t = text.trim();
  if (!t || t.length > 24) return false;
  return /^(?:\p{Extended_Pictographic}|\p{Emoji_Component}|‍|️|\s)+$/u.test(t);
}
